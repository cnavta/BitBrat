  public async setup(): Promise<void> {
    this.getLogger().info('tool_orchestrator.setup.start', {
      service: 'tool-orchestrator',
      mcpExposure: 'platform-only',
    });

    try {
      // Initialize PostgreSQL DocumentStore
      const store = await createDocumentStore();
      this.getLogger().info('tool_orchestrator.document_store_initialized');

      // Initialize ToolRegistry module
      this.toolRegistry = new ToolRegistry(store, this.getLogger() as any);
      this.getLogger().info('tool_orchestrator.tool_registry_initialized');

      // Initialize ModelRegistry module
      this.modelRegistry = new ModelRegistry(store, this.getLogger() as any);
      this.getLogger().info('tool_orchestrator.model_registry_initialized');

      // Initialize ToolGateway module (Sprint 62)
      this.toolGateway = new ToolGateway(
        this.toolRegistry,
        this.modelRegistry,
        {
          defaultTimeoutMs: 30000,
          cacheMaxSize: 1000,
          cacheTtlMs: 300000,
          enableLogging: true
        },
        undefined, // MCP client manager will be added later
        this.getLogger() as any
      );
      this.getLogger().info('tool_orchestrator.tool_gateway_initialized');

      // Initialize ToolObserver module (Sprint 59)
      const lokiUrl = process.env.LOKI_URL || 'http://localhost:3100';
      const lokiTimeoutMs = parseInt(process.env.LOKI_TIMEOUT_MS || '10000', 10);
      const healthyErrorThreshold = parseFloat(process.env.HEALTHY_ERROR_THRESHOLD || '0.05');
      const degradedErrorThreshold = parseFloat(process.env.DEGRADED_ERROR_THRESHOLD || '0.20');

      this.toolObserver = new ToolObserver(
        {
          url: lokiUrl,
          timeoutMs: lokiTimeoutMs,
          healthyErrorThreshold,
          degradedErrorThreshold,
        },
        this.getLogger() as any
      );
      this.getLogger().info('tool_orchestrator.tool_observer_initialized', {
        lokiUrl,
        lokiTimeoutMs,
        healthyErrorThreshold,
        degradedErrorThreshold,
      });

      // Initialize HealthUpdater module (Sprint 59)
      const healthUpdateIntervalMs = parseInt(
        process.env.HEALTH_UPDATE_INTERVAL_MS || '300000',
        10
      ); // Default: 5 minutes
      const healthStaleThresholdMs = parseInt(
        process.env.HEALTH_STALE_THRESHOLD_MS || '3600000',
        10
      ); // Default: 1 hour

      this.healthUpdater = new HealthUpdater(
        this.toolObserver,
        this.toolRegistry,
        {
          updateIntervalMs: healthUpdateIntervalMs,
          staleThresholdMs: healthStaleThresholdMs,
          healthyErrorThreshold,
          degradedErrorThreshold,
        },
        this.getLogger() as any
      );

      // Start background health updates
      this.healthUpdater.start();
      this.getLogger().info('tool_orchestrator.health_updater_started', {
        updateIntervalMs: healthUpdateIntervalMs,
        staleThresholdMs: healthStaleThresholdMs,
      });

      // Register MCP tools
      this.registerMcpTools();
      this.getLogger().info('tool_orchestrator.mcp_tools_registered');

      // Sprint 62: Task 1.4 - Load tools from PostgreSQL BEFORE starting MCP server
      // CRITICAL: This must happen before MCP server initialization so aggregated tools
      // are available when getMcpServer() is called
      await this.loadToolsFromRegistry();

      // Sprint 62: Task 3.1 - Periodic cache refresh (every 60 seconds)
      // Keeps tool registry changes synchronized without requiring service restart
      setInterval(async () => {
        try {
          await this.loadToolsFromRegistry();
        } catch (err) {
          this.getLogger().warn('tool_orchestrator.periodic_refresh_failed', {
            error: err instanceof Error ? err.message : String(err),
          });
        }
      }, 60000); // 60 seconds

      this.getLogger().info('tool_orchestrator.periodic_cache_refresh_enabled', {
        intervalMs: 60000,
      });

      // TODO: Seed model registry (Task 3.1) - run scripts/seed-model-registry.ts
      // TODO: Import tools from tool-gateway (Task 3.2) - to be done in integration testing

      this.getLogger().info('tool_orchestrator.setup.complete', {
        service: 'tool-orchestrator',
      });
    } catch (err) {
      this.getLogger().error('tool_orchestrator.setup_failed', {
        error: err instanceof Error ? err.message : String(err),
        stack: err instanceof Error ? err.stack : undefined,
      });
      throw err;
    }
  }

  public async close(reason: string = 'manual'): Promise<void> {
    this.getLogger().info('tool_orchestrator.shutdown', { reason });

    // Stop health updater
    if (this.healthUpdater) {
      this.healthUpdater.stop();
      this.getLogger().info('tool_orchestrator.health_updater_stopped');
    }

    await super.close(reason);
  }

